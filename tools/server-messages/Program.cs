    private static SyntaxNode? EnclosingMethod(SyntaxNode node)
        => node.Ancestors().FirstOrDefault(a => a is LocalFunctionStatementSyntax or MethodDeclarationSyntax or ConstructorDeclarationSyntax
            or PropertyDeclarationSyntax or AccessorDeclarationSyntax);

    private static string TypeName(SyntaxNode node) => node.Ancestors().OfType<TypeDeclarationSyntax>().FirstOrDefault()?.Identifier.Text ?? "";

    private static string NameOf(string text) {
        var plain = Regex.Replace(text, @"<[^>]+>", " ");
        plain = Regex.Replace(plain, @"\s+", " ").Trim();

        return plain.Length <= 60 ? plain : plain[..57].TrimEnd() + "...";
    }

