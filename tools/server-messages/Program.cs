/// <summary>One message's words, with its {holes} and where it is sent from.</summary>
internal sealed record FoundMessage(string Text, List<string> Fields, string Group, string Name, string When, string File, int Line) {

    internal string ToCSharp() {
        var key = "msg." + Convert.ToHexString(SHA1.HashData(Encoding.UTF8.GetBytes(Text)))[..10].ToLowerInvariant();
        var fields = Fields.Count == 0 ? "[]" : "[" + string.Join(", ", Fields.Select(f => $"({Literal("{" + f + "}")}, FILLED)")) + "]";

        return $"new({Literal(key)}, {Literal(Group)}, {Literal(Name)}, {Literal(When)}, {Literal(Text)}, {fields})";
    }

    private static string Literal(string text) => SymbolDisplay.FormatLiteral(text, quote: true);

}

internal sealed class MessageFinder(List<SyntaxTree> trees) {

    private const int MAX_VARIANTS = 12;
    private const string MESSAGE_TYPE = "MSG_SERVERMESSAGE";

    // A sink: a method (by its class and name, or by name alone when other classes can call it) whose parameter at
    // Index is sent as a server message.
    private readonly Dictionary<string, int> _sinksByName = [];
    private readonly Dictionary<(string Type, string Name), int> _sinksInType = [];
    private readonly List<FoundMessage> _found = [];

    internal int Unresolved { get; private set; }

    internal List<FoundMessage> Find() {
        FindSinks();
        if (Environment.GetEnvironmentVariable("SHOW_SINKS") is not null) {
            foreach (var (name, index) in _sinksByName) Console.Error.WriteLine($"shared {name} #{index}");
            foreach (var ((type, name), index) in _sinksInType) Console.Error.WriteLine($"{type}.{name} #{index}");
        }
        foreach (var tree in trees) {
            var rootNode = tree.GetRoot();
            foreach (var creation in rootNode.DescendantNodes().OfType<BaseObjectCreationExpressionSyntax>()) {
                if (MessageAssignment(creation) is { } words && !IsSinkBody(creation, words)) {
                    Add(tree, creation, words);
                }
            }

            foreach (var call in rootNode.DescendantNodes().OfType<InvocationExpressionSyntax>()) {
                if (SinkIndex(call) is { } index && index < call.ArgumentList.Arguments.Count
                    && !IsForwardedParameter(call, call.ArgumentList.Arguments[index].Expression)) {
                    Add(tree, call, call.ArgumentList.Arguments[index].Expression);
                }
            }
        }

        return _found;
    }

    private void FindSinks() {
        var changed = true;
        while (changed) {
            changed = false;
            foreach (var tree in trees) {
                var rootNode = tree.GetRoot();
                var candidates = rootNode.DescendantNodes().OfType<BaseObjectCreationExpressionSyntax>()
                    .Select(c => (Node: (SyntaxNode) c, Words: MessageAssignment(c)))
                    .Concat(rootNode.DescendantNodes().OfType<InvocationExpressionSyntax>()
                        .Select(c => (Node: (SyntaxNode) c, Words: SinkIndex(c) is { } i && i < c.ArgumentList.Arguments.Count
                            ? c.ArgumentList.Arguments[i].Expression : null)));
                foreach (var (node, words) in candidates) {
                    if (words is null || Unwrap(words) is not IdentifierNameSyntax name) {
                        continue;
                    }

                    var member = EnclosingMethod(node);
                    var parameters = member switch {
                        MethodDeclarationSyntax m => m.ParameterList.Parameters,
                        LocalFunctionStatementSyntax l => l.ParameterList.Parameters,
                        _ => default,
                    };
                    var index = parameters.IndexOf(p => p.Identifier.Text == name.Identifier.Text);
                    if (index < 0 || parameters[index].Type?.ToString() is not ("string" or "string?") || IsReassigned(member!, name.Identifier.Text)) {
                        continue;
                    }

                    var methodName = member switch {
                        MethodDeclarationSyntax m => m.Identifier.Text,
                        LocalFunctionStatementSyntax l => l.Identifier.Text,
                        _ => "",
                    };
                    var isShared = member is MethodDeclarationSyntax method
                        && method.Modifiers.Any(m => m.IsKind(SyntaxKind.ProtectedKeyword));
                    if (isShared) {
                        changed |= _sinksByName.TryAdd(methodName, index);
                    }
                    else {
                        changed |= _sinksInType.TryAdd((TypeName(member!), methodName), index);
                    }
                }
            }
        }
    }

    private static bool IsReassigned(SyntaxNode member, string name)
        => member.DescendantNodes().OfType<AssignmentExpressionSyntax>().Any(a => a.Left is IdentifierNameSyntax id && id.Identifier.Text == name);

    /// <summary>The words given to a MSG_SERVERMESSAGE's Message, when <paramref name="creation"/> builds one.</summary>
    private static ExpressionSyntax? MessageAssignment(BaseObjectCreationExpressionSyntax creation) {
        var isMessage = creation switch {
            ObjectCreationExpressionSyntax o => o.Type.ToString().EndsWith(MESSAGE_TYPE, StringComparison.Ordinal),
            ImplicitObjectCreationExpressionSyntax i => EnclosingMethod(i) is MethodDeclarationSyntax m
                && m.ReturnType.ToString().EndsWith(MESSAGE_TYPE, StringComparison.Ordinal),
            _ => false,
        };
        if (!isMessage || creation.Initializer is null) {
            return null;
        }

        return creation.Initializer.Expressions.OfType<AssignmentExpressionSyntax>()
            .FirstOrDefault(a => a.Left is IdentifierNameSyntax { Identifier.Text: "Message" })?.Right;
    }

    private bool IsSinkBody(SyntaxNode node, ExpressionSyntax words) => IsForwardedParameter(node, words);

    /// <summary>True when the words are just a parameter of a sink, which its callers give.</summary>
    private bool IsForwardedParameter(SyntaxNode node, ExpressionSyntax words) {
        if (Unwrap(words) is not IdentifierNameSyntax name) {
            return false;
        }

        var member = EnclosingMethod(node);
        var (methodName, parameters) = member switch {
            MethodDeclarationSyntax m => (m.Identifier.Text, m.ParameterList.Parameters),
            LocalFunctionStatementSyntax l => (l.Identifier.Text, l.ParameterList.Parameters),
            _ => ("", default),
        };
        var index = parameters.IndexOf(p => p.Identifier.Text == name.Identifier.Text);

        return index >= 0 && (_sinksByName.GetValueOrDefault(methodName, -1) == index
                              || _sinksInType.GetValueOrDefault((TypeName(member!), methodName), -1) == index);
    }

    private int? SinkIndex(InvocationExpressionSyntax call) {
        // A call in the sink's own class, or Class.Method(...) from elsewhere for a static one.
        var (type, name) = call.Expression switch {
            IdentifierNameSyntax id => (TypeName(call), id.Identifier.Text),
            MemberAccessExpressionSyntax { Expression: ThisExpressionSyntax or BaseExpressionSyntax } m => (TypeName(call), m.Name.Identifier.Text),
            MemberAccessExpressionSyntax { Expression: IdentifierNameSyntax owner } m => (owner.Identifier.Text, m.Name.Identifier.Text),
            MemberAccessExpressionSyntax { Expression: MemberAccessExpressionSyntax owner } m => (owner.Name.Identifier.Text, m.Name.Identifier.Text),
            _ => ("", ""),
        };
        if (name.Length == 0) {
            return null;
        }

        if (_sinksInType.TryGetValue((type, name), out var index)) {
            return index;
        }

        return call.Expression is IdentifierNameSyntax or MemberAccessExpressionSyntax { Expression: ThisExpressionSyntax or BaseExpressionSyntax }
               && _sinksByName.TryGetValue(name, out index) ? index : null;
    }

    private void Add(SyntaxTree tree, SyntaxNode at, ExpressionSyntax words) {
        var variants = Resolve(words, at, 0);
        if (variants is null) {
            // Announcements.Text: the Announcements tab has it already.
            return;
        }

        var file = tree.FilePath.Replace('\\', '/');
        var line = at.GetLocation().GetLineSpan().StartLinePosition.Line + 1;
        var (group, when) = GroupOf(file, at);
        var any = false;
        foreach (var variant in variants.Take(MAX_VARIANTS)) {
            var (text, fields) = variant.Render();
            var letters = Regex.Replace(Regex.Replace(text, @"\{[^{}]*\}", ""), @"[^A-Za-z]", "").Length;
            if (letters < 4) {
                continue;
            }

            any = true;
            _found.Add(new FoundMessage(text, fields, group, NameOf(text), when, file, line));
        }

        if (!any) {
            Unresolved++;
            if (Environment.GetEnvironmentVariable("SHOW_UNRESOLVED") is not null) {
                Console.Error.WriteLine($"{file}:{line}: {words}");
            }
        }
    }

    // ----- Turning an expression into words -----

    /// <summary>One way the words can come out: literal pieces and holes in order.</summary>
    private sealed class Words {

        internal readonly List<(bool IsHole, string Text)> Parts = [];

        internal Words Add(Words other) {
            var copy = Copy();
            copy.Parts.AddRange(other.Parts);

            return copy;
        }

        internal Words Copy() {
            var copy = new Words();
            copy.Parts.AddRange(Parts);

            return copy;
        }

        internal static Words Literal(string text) {
            var words = new Words();
            words.Parts.Add((false, text));

            return words;
        }

        internal static Words Hole(string name) {
            var words = new Words();
            words.Parts.Add((true, name));

            return words;
        }

        internal (string Text, List<string> Fields) Render() {
            var text = new StringBuilder();
            var fields = new List<string>();
            var lastWasHole = false;
            foreach (var (isHole, part) in Parts) {
                if (isHole) {
                    if (lastWasHole) {
                        // Two holes side by side cannot be told apart in a sent message: they are one.
                        continue;
                    }

                    var name = part;
                    for (var n = 2; fields.Contains(name); n++) {
                        name = $"{part} {n}";
                    }

                    fields.Add(name);
                    text.Append('{').Append(name).Append('}');
                    lastWasHole = true;
                }
                else if (part.Length > 0) {
                    text.Append(part);
                    lastWasHole = false;
                }
            }

            return (text.ToString(), fields);
        }

    }

    /// <summary>The ways <paramref name="expression"/> can come out, or null when it is an Announcements line.</summary>
    private List<Words>? Resolve(ExpressionSyntax expression, SyntaxNode at, int depth) {
        expression = Unwrap(expression);
        if (depth > 6) {
            return [Words.Hole(HoleName(expression))];
        }

        switch (expression) {
            case LiteralExpressionSyntax literal when literal.IsKind(SyntaxKind.StringLiteralExpression):
                return [Words.Literal(literal.Token.ValueText)];
            case LiteralExpressionSyntax literal when literal.IsKind(SyntaxKind.NullLiteralExpression):
                return [];
            case InterpolatedStringExpressionSyntax interpolated: {
                List<Words> result = [new Words()];
                foreach (var content in interpolated.Contents) {
                    List<Words> part = content switch {
                        InterpolatedStringTextSyntax text => [Words.Literal(text.TextToken.ValueText)],
                        InterpolationSyntax hole => ResolveHole(hole.Expression, at, depth),
                        _ => [new Words()],
                    };
                    result = Combine(result, part);
                }

                return result;
            }
            case BinaryExpressionSyntax binary when binary.IsKind(SyntaxKind.AddExpression): {
                var left = Resolve(binary.Left, at, depth + 1);
                var right = Resolve(binary.Right, at, depth + 1);
                if (left is null || right is null) {
                    return null;
                }

                return Combine(left, right);
            }
            case BinaryExpressionSyntax binary when binary.IsKind(SyntaxKind.CoalesceExpression):
                return Either(Resolve(binary.Left, at, depth + 1), Resolve(binary.Right, at, depth + 1));
            case ConditionalExpressionSyntax conditional:
                return Either(Resolve(conditional.WhenTrue, at, depth + 1), Resolve(conditional.WhenFalse, at, depth + 1));
            case SwitchExpressionSyntax switchExpression: {
                List<Words>? all = [];
                foreach (var arm in switchExpression.Arms) {
                    all = Either(all, Resolve(arm.Expression, at, depth + 1));
                }

                return all;
            }
            case InvocationExpressionSyntax call when IsAnnouncement(call):
                return null;
            case InvocationExpressionSyntax call when ReturnedWords(call) is { Count: > 0 } returns: {
                List<Words>? all = [];
                foreach (var returned in returns) {
                    all = Either(all, Resolve(returned, returned, depth + 1));
                }

                return all is { Count: > 0 } ? all : [Words.Hole(HoleName(expression))];
            }
            case IdentifierNameSyntax name when ValuesOf(name, at) is { Count: > 0 } values: {
                List<Words>? all = [];
                foreach (var value in values) {
                    all = Either(all, Resolve(value, value, depth + 1));
                }

                return all is { Count: > 0 } ? all : [Words.Hole(HoleName(expression))];
            }
            default:
                return [Words.Hole(HoleName(expression))];
        }
    }

    /// <summary>A {hole} of a $"..." is words of its own only when it is a word choice (a ?: or switch of strings).</summary>
    private List<Words> ResolveHole(ExpressionSyntax expression, SyntaxNode at, int depth) {
        var inner = Unwrap(expression);
        if (inner is ConditionalExpressionSyntax or SwitchExpressionSyntax or LiteralExpressionSyntax) {
            var resolved = Resolve(inner, at, depth + 1);
            if (resolved is { Count: > 0 } && resolved.Count <= 4) {
                return resolved;
            }
        }

        return [Words.Hole(HoleName(expression))];
    }

    private static List<Words> Combine(List<Words> left, List<Words> right) {
        if (left.Count * right.Count > MAX_VARIANTS) {
            // Too many ways: keep the first of each, which still matches the rest through its holes' text.
            return [left[0].Add(right[0])];
        }

        return [.. left.SelectMany(l => right.Select(r => l.Add(r)))];
    }

    private static List<Words>? Either(List<Words>? a, List<Words>? b) {
        if (a is null && b is null) {
            return null;
        }

        return [.. (a ?? []).Concat(b ?? [])];
    }

    private static bool IsAnnouncement(InvocationExpressionSyntax call) {
        var text = call.Expression.ToString();

        return text.EndsWith("Announcements.Text", StringComparison.Ordinal) || text.EndsWith("AnnouncementBox", StringComparison.Ordinal)
            || text.EndsWith("AnnouncementChat", StringComparison.Ordinal);
    }

    /// <summary>What a local, a const or a field of the same class is set to.</summary>
    private List<ExpressionSyntax> ValuesOf(IdentifierNameSyntax name, SyntaxNode at) {
        var id = name.Identifier.Text;
        var values = new List<ExpressionSyntax>();
        if (EnclosingMethod(at) is { } member) {
            foreach (var declarator in member.DescendantNodes().OfType<VariableDeclaratorSyntax>()) {
                if (declarator.Identifier.Text == id && declarator.Initializer is not null) {
                    values.Add(declarator.Initializer.Value);
                }
            }

            foreach (var assignment in member.DescendantNodes().OfType<AssignmentExpressionSyntax>()) {
                if (assignment.IsKind(SyntaxKind.SimpleAssignmentExpression) && assignment.Left is IdentifierNameSyntax left && left.Identifier.Text == id) {
                    values.Add(assignment.Right);
                }
            }

            foreach (var pattern in member.DescendantNodes().OfType<SingleVariableDesignationSyntax>()) {
                if (pattern.Identifier.Text != id) {
                    continue;
                }

                if (pattern.Parent?.Parent is IsPatternExpressionSyntax isPattern) {
                    values.Add(isPattern.Expression);
                }
                else if (pattern.Parent is DeclarationExpressionSyntax { Parent: ArgumentSyntax { RefKindKeyword.Text: "out" } argument }
                         && argument.Parent?.Parent is InvocationExpressionSyntax call) {
                    values.AddRange(OutWords(call, argument));
                }
            }

            foreach (var argument in member.DescendantNodes().OfType<ArgumentSyntax>()) {
                if (argument.RefKindKeyword.Text == "out" && argument.Expression is IdentifierNameSyntax outName && outName.Identifier.Text == id
                    && argument.Parent?.Parent is InvocationExpressionSyntax call) {
                    values.AddRange(OutWords(call, argument));
                }
            }

            if (values.Count > 0) {
                return values;
            }
        }

        if (at.Ancestors().OfType<TypeDeclarationSyntax>().FirstOrDefault() is { } type) {
            foreach (var field in type.Members.OfType<FieldDeclarationSyntax>()) {
                foreach (var declarator in field.Declaration.Variables) {
                    if (declarator.Identifier.Text == id && declarator.Initializer is not null
                        && field.Modifiers.Any(m => m.IsKind(SyntaxKind.ConstKeyword) || m.IsKind(SyntaxKind.ReadOnlyKeyword))) {
                        values.Add(declarator.Initializer.Value);
                    }
                }
            }
        }

        return values;
    }

    private Dictionary<string, List<TypeDeclarationSyntax>>? _types;

    /// <summary>What a method sets one of its out parameters to.</summary>
    private List<ExpressionSyntax> OutWords(InvocationExpressionSyntax call, ArgumentSyntax argument) {
        var method = MethodOf(call);
        var index = call.ArgumentList.Arguments.IndexOf(argument);
        if (method is null || index < 0 || index >= method.ParameterList.Parameters.Count) {
            return [];
        }

        var parameter = method.ParameterList.Parameters[index].Identifier.Text;

        return [.. method.DescendantNodes().OfType<AssignmentExpressionSyntax>()
            .Where(a => a.IsKind(SyntaxKind.SimpleAssignmentExpression) && a.Left is IdentifierNameSyntax left && left.Identifier.Text == parameter)
            .Select(a => a.Right)];
    }

    private MethodDeclarationSyntax? MethodOf(InvocationExpressionSyntax call) {
        _types ??= trees.SelectMany(t => t.GetRoot().DescendantNodes().OfType<TypeDeclarationSyntax>())
            .GroupBy(t => t.Identifier.Text).ToDictionary(g => g.Key, g => g.ToList());
        var (typeName, methodName) = call.Expression switch {
            IdentifierNameSyntax id => (TypeName(call), id.Identifier.Text),
            MemberAccessExpressionSyntax { Expression: ThisExpressionSyntax } m => (TypeName(call), m.Name.Identifier.Text),
            MemberAccessExpressionSyntax { Expression: IdentifierNameSyntax owner } m => (owner.Identifier.Text, m.Name.Identifier.Text),
            MemberAccessExpressionSyntax { Expression: MemberAccessExpressionSyntax owner } m => (owner.Name.Identifier.Text, m.Name.Identifier.Text),
            _ => ("", ""),
        };

        return _types.GetValueOrDefault(typeName)?.SelectMany(t => t.Members.OfType<MethodDeclarationSyntax>())
            .FirstOrDefault(m => m.Identifier.Text == methodName && m.ParameterList.Parameters.Count >= call.ArgumentList.Arguments.Count);
    }

    /// <summary>What a method that gives words returns: one of the same class, or Class.Method(...) of another.</summary>
    private List<ExpressionSyntax> ReturnedWords(InvocationExpressionSyntax call) {
        _types ??= trees.SelectMany(t => t.GetRoot().DescendantNodes().OfType<TypeDeclarationSyntax>())
            .GroupBy(t => t.Identifier.Text).ToDictionary(g => g.Key, g => g.ToList());
        var (typeName, methodName) = call.Expression switch {
            IdentifierNameSyntax id => (TypeName(call), id.Identifier.Text),
            MemberAccessExpressionSyntax { Expression: ThisExpressionSyntax } m => (TypeName(call), m.Name.Identifier.Text),
            MemberAccessExpressionSyntax { Expression: IdentifierNameSyntax owner } m => (owner.Identifier.Text, m.Name.Identifier.Text),
            MemberAccessExpressionSyntax { Expression: MemberAccessExpressionSyntax owner } m => (owner.Name.Identifier.Text, m.Name.Identifier.Text),
            _ => ("", ""),
        };
        var method = _types.GetValueOrDefault(typeName)?.SelectMany(t => t.Members.OfType<MethodDeclarationSyntax>())
            .FirstOrDefault(m => m.Identifier.Text == methodName && m.ReturnType.ToString() is "string" or "string?"
                                 && m.ParameterList.Parameters.Count >= call.ArgumentList.Arguments.Count);
        if (method is null) {
            return [];
        }

        if (method.ExpressionBody is { } body) {
            return [body.Expression];
        }

        return [.. method.Body?.DescendantNodes().OfType<ReturnStatementSyntax>()
            .Where(r => r.Expression is not null && r.Ancestors().OfType<LocalFunctionStatementSyntax>().FirstOrDefault() is null
                        && r.Ancestors().OfType<LambdaExpressionSyntax>().FirstOrDefault() is null)
            .Select(r => r.Expression!) ?? []];
    }

    private static ExpressionSyntax Unwrap(ExpressionSyntax expression) {
        while (true) {
            switch (expression) {
                case ParenthesizedExpressionSyntax p:
                    expression = p.Expression;
                    break;
                case PostfixUnaryExpressionSyntax u when u.IsKind(SyntaxKind.SuppressNullableWarningExpression):
                    expression = u.Operand;
                    break;
                case CastExpressionSyntax c:
                    expression = c.Expression;
                    break;
                default:
                    return expression;
            }
        }
    }

    private static readonly HashSet<string> s_plainEnds = ["Name", "Count", "Value", "Text", "Length", "Key", "Id", "ID", "Title", "Amount", "Level"];

    /// <summary>A short name for a hole, from what fills it: count, item name, wizard name ...</summary>
    private static string HoleName(ExpressionSyntax expression) {
        expression = Unwrap(expression);
        var pieces = new List<string>();
        var current = expression;
        while (pieces.Count < 3) {
            switch (current) {
                case InvocationExpressionSyntax call:
                    current = call.Expression;
                    continue;
                case MemberAccessExpressionSyntax member:
                    pieces.Insert(0, member.Name.Identifier.Text);
                    current = member.Expression;
                    continue;
                case ConditionalAccessExpressionSyntax conditional:
                    current = conditional.Expression;
                    continue;
                case IdentifierNameSyntax id:
                    pieces.Insert(0, id.Identifier.Text);
                    break;
                case ElementAccessExpressionSyntax element:
                    current = element.Expression;
                    continue;
            }

            break;
        }

        if (expression is ConditionalAccessExpressionSyntax access) {
            pieces.Add(access.WhenNotNull.ToString().Split('.', StringSplitOptions.RemoveEmptyEntries).LastOrDefault()?.Split('(')[0] ?? "");
        }

        pieces = [.. pieces.Where(p => p.Length > 0 && p is not ("ToString" or "Trim" or "ToLower" or "ToLowerInvariant" or "ToUpper" or "Value"))];
        if (pieces.Count == 0) {
            return "value";
        }

        var last = pieces[^1];
        var useful = s_plainEnds.Contains(last) && pieces.Count > 1 ? $"{pieces[^2]} {last}" : last;
        useful = Regex.Replace(useful, @"^(s_|_|m_)", "");
        useful = Regex.Replace(useful, @"^Get(?=[A-Z])", "");
        useful = Regex.Replace(useful, @"(?<=[a-z0-9])(?=[A-Z])", " ").Replace('_', ' ').Trim().ToLowerInvariant();
        useful = Regex.Replace(useful, @"\s+", " ");

        return useful.Length is 0 or > 30 ? "value" : useful;
    }

