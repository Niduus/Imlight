    private static (string Group, string When) GroupOf(string file, SyntaxNode at) {
        var group = s_groups.FirstOrDefault(g => Regex.IsMatch(file, g.Pattern)).Group ?? "Other places";
        if (group == "Commands") {
            var command = at.Ancestors().OfType<MethodDeclarationSyntax>()
                .SelectMany(m => m.AttributeLists.SelectMany(l => l.Attributes))
                .FirstOrDefault(a => a.Name.ToString() is "Command" or "CommandAttribute")?.ArgumentList?.Arguments.FirstOrDefault()?.ToString().Trim('"');
            var commandGroup = at.Ancestors().OfType<ClassDeclarationSyntax>()
                .SelectMany(c => c.AttributeLists.SelectMany(l => l.Attributes))
                .FirstOrDefault(a => a.Name.ToString() is "CommandGroup" or "CommandGroupAttribute")?.ArgumentList?.Arguments.FirstOrDefault()?.ToString().Trim('"');
            var full = string.Join(' ', new[] { commandGroup, command }.Where(p => !string.IsNullOrEmpty(p)));

            return (group, full.Length > 0 ? $"The player who typed .{full}." : "The player who typed a command.");
        }

        return (group, group switch {
            "Pet hatching" => "The player hatching pets.",
            "Gardening" => "The player gardening.",
            "Battles" => "A player in battle.",
            "Events" => "A player during an event.",
            _ => "The player it is about.",
        });
    }

